"""Generate recomp/runtime/host/xdk_ret_bytes.inc: how many argument bytes each
named XDK library function pops when it returns, in the game's own build.

The native replacements are registered by name (xdk_symbols.inc) and were
written against another XDK build; the runtime checks each call against this
table, so a function whose arguments differ between the builds stops the
runtime at its first call, named, instead of unbalancing the stack.

    qilin insns <default.xbe> --linear -o linear.insns.txt
    python3 tools/gen/xdk_ret_bytes.py linear.insns.txt

The function's code is walked from its start (fall-through and direct jumps,
no further than the next named symbol) and every `ret` reached must pop the
same; a function with none (a thunk, a tail call) or with two answers gets no
entry and is not checked. The output holds names and small numbers only."""
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
if len(sys.argv) != 2:
    sys.exit(__doc__)
symbols = []
for line in (ROOT / "recomp/runtime/host/xdk_symbols.inc").read_text().splitlines():
    m = re.match(r'\{0x([0-9A-F]+), "(\w+)", "(\w+)"\}', line)
    if m:
        symbols.append((int(m.group(1), 16), m.group(2), m.group(3)))
symbols.sort()
starts = [a for a, _, _ in symbols]
insns = []
for line in open(sys.argv[1]):
    parts = line.rstrip("\n").split("\t")
    head = parts[0].split()
    insns.append((int(head[0], 16), head[-1] if len(head) >= 4 else "bad", parts[-1]))
addrs = [a for a, _, _ in insns]
by_addr = {a: i for i, a in enumerate(addrs)}
rows = []
for k, (addr, lib, name) in enumerate(symbols):
    end = starts[k + 1] if k + 1 < len(starts) else addr + 0x4000
    if addr not in by_addr:
        continue  # a variable, or not an instruction boundary
    # Walk the function's own code: fall-through and direct jumps that stay
    # between this symbol and the next. Every `ret` reached must agree.
    pops, todo, done, sound = set(), [addr], set(), True
    while todo:
        a = todo.pop()
        while a not in done and addr <= a < end and a in by_addr:
            done.add(a)
            _, mnem, text = insns[by_addr[a]]
            size = insns[by_addr[a] + 1][0] - a if by_addr[a] + 1 < len(insns) else 0
            if mnem == "ret":
                m = re.fullmatch(r"ret(?: 0x([0-9A-Fa-f]+))?", text)
                if m:
                    pops.add(int(m.group(1), 16) if m.group(1) else 0)
                else:
                    sound = False
                break
            if mnem in ("bad", "int3"):
                break
            m = re.fullmatch(r"j\w+ 0x([0-9A-Fa-f]+)", text)
            if m:
                todo.append(int(m.group(1), 16))
            if mnem == "jmp":
                break
            a += size
    if sound and len(pops) == 1:
        rows.append((name, pops.pop()))
seen = set()
out = ["// Generated by tools/gen/xdk_ret_bytes.py from the game's own build. Do not edit.",
       "// {XDK library function, argument bytes its return pops}"]
for name, n in rows:
    if name not in seen:
        seen.add(name)
        out.append(f'{{"{name}", {n}}},')
(ROOT / "recomp/runtime/host/xdk_ret_bytes.inc").write_text("\n".join(out) + "\n")
print(len(seen), "functions")
